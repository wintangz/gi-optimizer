export type GiSlotKey = 'flower' | 'plume' | 'sands' | 'goblet' | 'circlet'
export type GiElementWithPhyKey =
  | 'anemo'
  | 'cryo'
  | 'dendro'
  | 'electro'
  | 'geo'
  | 'hydro'
  | 'physical'
  | 'pyro'
export type GiWeaponTypeKey = 'sword' | 'claymore' | 'polearm' | 'bow' | 'catalyst'

const ELEMENT_WITH_PHY_KEYS: readonly GiElementWithPhyKey[] = [
  'anemo',
  'cryo',
  'dendro',
  'electro',
  'geo',
  'hydro',
  'physical',
  'pyro',
]

export function SlotIcon({
  slotKey,
  iconProps = {},
}: {
  slotKey: GiSlotKey
  iconProps?: GiSvgIconProps
}) {
  switch (slotKey) {
    case 'flower':
      return <FlowerIcon {...iconProps} />
    case 'plume':
      return <PlumeIcon {...iconProps} />
    case 'sands':
      return <SandsIcon {...iconProps} />
    case 'goblet':
      return <GobletIcon {...iconProps} />
    case 'circlet':
      return <CircletIcon {...iconProps} />
  }
}

export function ElementIcon({
  ele,
  iconProps = {},
}: {
  ele: GiElementWithPhyKey
  iconProps?: GiSvgIconProps
}) {
  switch (ele) {
    case 'anemo':
      return <AnemoIcon {...iconProps} />
    case 'cryo':
      return <CryoIcon {...iconProps} />
    case 'dendro':
      return <DendroIcon {...iconProps} />
    case 'electro':
      return <ElectroIcon {...iconProps} />
    case 'geo':
      return <GeoIcon {...iconProps} />
    case 'hydro':
      return <HydroIcon {...iconProps} />
    case 'physical':
      return <PhysicalIcon {...iconProps} />
    case 'pyro':
      return <PyroIcon {...iconProps} />
  }
}

export function WeaponTypeIcon({
  weaponType,
  iconProps = {},
}: {
  weaponType: GiWeaponTypeKey
  iconProps?: GiSvgIconProps
}) {
  switch (weaponType) {
    case 'sword':
      return <SwordIcon {...iconProps} />
    case 'claymore':
      return <ClaymoreIcon {...iconProps} />
    case 'polearm':
      return <PolearmIcon {...iconProps} />
    case 'bow':
      return <BowIcon {...iconProps} />
    case 'catalyst':
      return <CatalystIcon {...iconProps} />
  }
}

export function resolveStatElement(statKey: string): GiElementWithPhyKey | null {
  const ele = statKey.split('_')[0] as GiElementWithPhyKey
  if (ELEMENT_WITH_PHY_KEYS.includes(ele)) return ele
  return null
}

export function hasStatIcon(statKey: string): boolean {
  switch (statKey) {
    case 'hp':
    case 'hp_':
    case 'base_hp':
    case 'atk':
    case 'atk_':
    case 'base_atk':
    case 'def':
    case 'def_':
    case 'base_def':
    case 'eleMas':
    case 'critRate_':
    case 'critDMG_':
    case 'enerRech_':
    case 'incHeal_':
    case 'heal_':
    case 'cdRed_':
    case 'shield_':
    case 'stamina':
      return true
  }
  return resolveStatElement(statKey) !== null
}

export function StatIcon({
  statKey,
  iconProps = {},
}: {
  statKey: string
  iconProps?: GiSvgIconProps
}) {
  switch (statKey) {
    case 'hp':
    case 'hp_':
    case 'base_hp':
      return <HpIcon {...iconProps} />
    case 'atk':
    case 'atk_':
    case 'base_atk':
      return <AtkIcon {...iconProps} />
    case 'def':
    case 'def_':
    case 'base_def':
      return <DefIcon {...iconProps} />
    case 'eleMas':
      return <EleMasIcon {...iconProps} />
    case 'critRate_':
      return <CritRateIcon {...iconProps} />
    case 'critDMG_':
      return <CritDmgIcon {...iconProps} />
    case 'enerRech_':
      return <EnerRechIcon {...iconProps} />
    case 'incHeal_':
      return <HealAddIcon {...iconProps} />
    case 'heal_':
      return <HealingBonusIcon {...iconProps} />
    case 'cdRed_':
      return <CdRedIcon {...iconProps} />
    case 'shield_':
      return <ShieldStrIcon {...iconProps} />
    case 'stamina':
      return <StaminaIcon {...iconProps} />
  }
  const ele = resolveStatElement(statKey)
  if (ele) return <ElementIcon ele={ele} iconProps={iconProps} />
  return null
}
